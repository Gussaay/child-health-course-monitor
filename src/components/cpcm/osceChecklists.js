export const osceSteps = (checklist) =>
    (checklist?.sections || []).flatMap(s => s.entries.filter(e => e.id));

// answers: { [stepId]: 'done' | 'not_done' }. A step left blank counts as
// not done, as the forms say for steps that were not completed fully.
export function scoreOsce(checklist, answers = {}) {
    const steps = osceSteps(checklist);
    const total = steps.length;
    const score = steps.filter(s => answers[s.id] === 'done').length;
    const answered = steps.filter(s => answers[s.id] === 'done' || answers[s.id] === 'not_done').length;
    const criticalMissed = steps.filter(s => s.critical && answers[s.id] !== 'done').map(s => s.id);
    const passMark = checklist?.passMark ?? total;
    const passed = total > 0 && score >= passMark && criticalMissed.length === 0;
    const percentage = total ? Math.round((score / total) * 1000) / 10 : 0;
    return { score, total, answered, passMark, criticalMissed, passed, percentage };
}

// Builds what is stored on the participant under osce_results[checklistId].
// The first saved score is kept as firstScore, which the bag-and-mask form
// asks for ("score at the first attempt").
export function buildOsceRecord(checklist, answers, previous, { assessor, notes, now = new Date() } = {}) {
    const result = scoreOsce(checklist, answers);
    return {
        checklistId: checklist.id,
        answers: { ...answers },
        score: result.score,
        total: result.total,
        passMark: result.passMark,
        passed: result.passed,
        criticalMissed: result.criticalMissed,
        percentage: result.percentage,
        firstScore: previous?.firstScore ?? result.score,
        notes: notes || '',
        assessor: assessor || previous?.assessor || '',
        assessedAt: previous?.assessedAt || now.toISOString(),
        updatedAt: now.toISOString(),
    };
}
