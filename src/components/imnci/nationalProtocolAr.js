const DOSE_AT_END = /^(.*?)(\s*[:—-]?\s*)(\{\{dose:[^}]+\}\})\s*$/;

/** The Arabic of one line, with its dose tag kept at the end. */
export const toArabic = (line) => {
    const text = String(line ?? '');
    const m = text.match(DOSE_AT_END);
    if (m) {
        const ar = AR[m[1].trim()];
        return ar ? `${ar}: ${m[3]}` : undefined;
    }
    return AR[text.trim()];
};
